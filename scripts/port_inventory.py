#!/usr/bin/env python3
"""Generate a factual inventory from the retained source and declared port status.

The status manifest is author-maintained, not a proof of implementation. Missing
operations/targets are always shown as unimplemented. No source module is marked
fully ported merely because a related prototype exists.
"""
import argparse
import json
from pathlib import Path
import re

ROOT = Path(__file__).resolve().parents[1]


def report():
    status = json.loads((ROOT / 'port-status.json').read_text())
    source = ROOT / 'third_party/qbe'
    public, internal = (source / 'ops.h').read_text().split('/* INTERNAL OPERATIONS', 1)
    names = lambda text: re.findall(r'^O\((\w+),', text, re.MULTILINE)
    operations, private = names(public), names(internal)
    assert set(status['operations']) <= set(operations), 'status names unknown upstream operation'
    targets = sorted(name for path in source.glob('*/targ.c')
                     for name in re.findall(r'\.name = "([^"]+)"', path.read_text()))
    assert set(status['targets']) <= set(targets), 'status names unknown upstream target'
    tests = sorted(source.glob('test/*.ssa'))
    modules = sorted(path.relative_to(source) for path in source.rglob('*')
                     if path.suffix in ('.c', '.h') and 'minic' not in path.parts and 'tools' not in path.parts)
    lines = ['# QBE port inventory', '',
             'Generated by `nix develop -c python3 scripts/port_inventory.py --write`.',
             'Source: pinned QBE 1.3; status: author-maintained `port-status.json`.',
             'Counts describe inventory, not correctness or complete compatibility.', '',
             f'- {len(operations)} public opcode names; {len(status["operations"])} currently accept some forms.',
             f'- {len(private)} internal opcode names; no complete internal-operation port yet.',
             f'- {len(targets)} upstream target/ABI configurations; one partial initial target.',
             f'- {len(modules)} compiler C/header modules; no complete module-for-module port yet.',
             f'- {len(tests)} upstream SSA fixtures retained; partial qualification is tracked in [UPSTREAM_COVERAGE.md](UPSTREAM_COVERAGE.md).', '',
             'A supported opcode name may have unimplemented types (especially floating point).',
             'Integer-parameter ABI tests and generated programs do not qualify the full upstream suite.', '',
             '## Public operations', '', '| Opcode | Accepted result/value forms |', '| --- | --- |']
    for op in operations:
        supported = ', '.join(status['operations'].get(op, [])) or 'not implemented'
        lines.append(f'| `{op}` | {supported} |')
    lines += ['', '## Syntax and passes', '', '| Area | Status |', '| --- | --- |']
    for name, value in list(status['syntax'].items()) + list(status['passes'].items()):
        lines.append(f'| {name} | {value} |')
    lines += ['', '## Targets and ABIs', '', '| Upstream name | Status |', '| --- | --- |']
    for target in targets:
        lines.append(f'| `{target}` | {status["targets"].get(target, "not implemented")} |')
    lines += ['', '## Source modules', '',
              'All are retained unchanged as references. The following list is the scope',
              'of the eventual port, not a list of translated Lean modules.', '']
    lines += [f'- `{path}`' for path in modules]
    lines += ['', '## Internal operation names', '', ', '.join(f'`{name}`' for name in private) + '.', '']
    return '\n'.join(lines)


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--write', action='store_true')
    options = parser.parse_args()
    path = ROOT / 'docs/PORT_STATUS.md'
    result = report()
    if options.write: path.write_text(result)
    else: assert path.read_text() == result, 'port inventory drift: regenerate the report'
    print('QBE source/operation/target inventory: consistent')


if __name__ == '__main__': main()
