#!/usr/bin/env python3
"""Bind the pure compiler implementation and pinned build configuration to jobs.

This is a source/build-config identity, not a native executable attestation.
Proof-only and test sources do not affect code dependencies. CI rejects stale
manifests; use --write after changing compiler implementation files.
"""
import argparse
import hashlib
import json
import subprocess
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
GENERATED = ROOT/'LeanCompilerBackend/Verified/BuildIdentity.lean'
MANIFEST = ROOT/'compiler-build.json'
EXCLUDED = {'BuildIdentity.lean','MachineProofs.lean','BindingProofs.lean','LayoutProofs.lean','FrameProofs.lean','EntryProofs.lean','EntryExamples.lean','TransferProofs.lean','PhiSwapProof.lean','PhiExamples.lean','DivergenceProofs.lean','OperandProofs.lean','StagingProofs.lean','CommitProofs.lean','SourceTransferProofs.lean','InstructionProofs.lean','ArithmeticProofs.lean','ComparisonProofs.lean','PhiContextProofs.lean','Tests.lean','JobTests.lean','CodecTests.lean'}


def expected():
    sources = [p for p in (ROOT/'LeanCompilerBackend').rglob('*.lean') if p.name not in EXCLUDED]
    sources += [ROOT/p for p in ['Main.lean','LeanCompilerBackend.lean','lakefile.toml','lake-manifest.json','lean-toolchain','flake.nix','flake.lock']]
    entries = {p.relative_to(ROOT).as_posix(): hashlib.sha256(p.read_bytes()).hexdigest()
               for p in sorted(sources)}
    # The field/encoding/version is part of the identity protocol.
    payload = json.dumps({'schema':1,'files':entries},sort_keys=True,separators=(',',':')).encode()
    digest = hashlib.sha256(b'LCB-compiler-source-build-v1\0'+payload).hexdigest()
    manifest = json.dumps({'schema':1,'identity':digest,'files':entries},indent=2,sort_keys=True)+'\n'
    lean = ('/- Generated by scripts/build_identity.py --write; do not edit. -/\n'
            'namespace LeanCompilerBackend.Verified\n'
            f'def compilerBuildIdentity : String := "{digest}"\n'
            'end LeanCompilerBackend.Verified\n')
    return manifest, lean


def main():
    parser=argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--write',action='store_true')
    parser.add_argument('--check-binary',action='store_true')
    args=parser.parse_args()
    manifest,lean=expected()
    if args.write:
        MANIFEST.write_text(manifest)
        GENERATED.write_text(lean)
    else:
        assert MANIFEST.exists() and GENERATED.exists(), 'missing compiler identity; run scripts/build_identity.py --write'
        assert MANIFEST.read_text()==manifest and GENERATED.read_text()==lean, 'stale compiler identity; run scripts/build_identity.py --write, then rebuild'
    if args.check_binary:
        actual=subprocess.check_output([ROOT/'.lake/build/bin/lcb','--build-identity'],text=True).strip()
        assert actual==json.loads(manifest)['identity'], 'stale compiler executable; rebuild lcb before qualification'
    print('compiler source/build identity: consistent')


if __name__=='__main__':
    main()
